"""Rebuild the CRC-32 verify loader and regenerate lib/core/loader/crc32_blob.inc.

    ../../.venv/bin/python build.py            (needs arm-none-eabi-gcc: ARM_GCC_BIN or ~/arm/.../bin)

Steps: compile (ARMv6-M Thumb, position independent), extract the flat binary and the symbol offsets, verify the blob
in the unicorn emulator against zlib.crc32 (several lengths, two load addresses, chained calls), write the .inc.
The library build never needs arm-gcc: it only includes the generated, checked-in .inc.
"""
import glob
import os
import random
import struct
import subprocess
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "lib", "core", "loader", "crc32_blob.inc")
BIN = os.environ.get("ARM_GCC_BIN") or (glob.glob(os.path.expanduser("~/arm/arm-gnu-toolchain-*/bin")) or [""])[0]
CFLAGS = ["-mcpu=cortex-m0plus", "-mthumb", "-mfloat-abi=soft", "-O2", "-fpie", "-ffreestanding", "-nostdlib",
          "-fno-builtin", "-ffunction-sections", "-fno-jump-tables", "-Wall", "-Wextra", "-Wconversion", "-Werror"]


def tool(name):
    return os.path.join(BIN, "arm-none-eabi-" + name)


def build(tmp):
    src, ld = os.path.join(HERE, "crc32_ldr.c"), os.path.join(HERE, "crc32_ldr.ld")
    obj, elf, binf = (os.path.join(tmp, "crc32." + x) for x in ("o", "elf", "bin"))
    subprocess.run([tool("gcc")] + CFLAGS + ["-c", src, "-o", obj], check=True)
    subprocess.run([tool("gcc"), "-mcpu=cortex-m0plus", "-mthumb", "-nostdlib", "-Wl,-T," + ld,
                    "-Wl,--no-warn-rwx-segments", obj, "-o", elf], check=True)
    subprocess.run([tool("objcopy"), "-O", "binary", elf, binf], check=True)
    relocs = subprocess.run([tool("readelf"), "-r", elf], check=True, capture_output=True, text=True).stdout
    if "Relocation section" in relocs:
        sys.exit("loader has relocations: not position independent")
    syms = {}
    for line in subprocess.run([tool("nm"), elf], check=True, capture_output=True, text=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2].startswith("crc32_"):
            syms[parts[2]] = int(parts[0], 16)
    blob = open(binf, "rb").read()
    blob += b"\0" * (-len(blob) % 4)
    version = subprocess.run([tool("gcc"), "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    return blob, syms, version


def emulate(blob, syms, base, data_addr, data, chunk):
    """Run init + chained updates like the probe does; return the CRC."""
    from unicorn import Uc, UC_ARCH_ARM, UC_MODE_THUMB, UC_MODE_MCLASS
    from unicorn.arm_const import UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3, UC_ARM_REG_SP, \
        UC_ARM_REG_LR
    mu = Uc(UC_ARCH_ARM, UC_MODE_THUMB | UC_MODE_MCLASS)
    mu.mem_map(0x00000000, 0x200000)
    mu.mem_map(0x20000000, 0x40000)
    mu.mem_write(base, blob)
    mu.mem_write(data_addr, data)
    tab, trap = base + 0x400, base + (syms["crc32_trap"] & ~1)

    def call(fn, args):
        for reg, v in zip((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3), args):
            mu.reg_write(reg, v)
        mu.reg_write(UC_ARM_REG_SP, base + 0x1000)
        mu.reg_write(UC_ARM_REG_LR, trap | 1)
        mu.emu_start((base + fn) | 1, trap, count=50_000_000)
        return mu.reg_read(UC_ARM_REG_R0)

    call(syms["crc32_init"] & ~1, [tab])
    crc, off = 0, 0
    while off < len(data):
        n = min(chunk, len(data) - off)
        crc = call(syms["crc32_update"] & ~1, [data_addr + off, n, tab, crc])
        off += n
    return crc


def main():
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        blob, syms, version = build(tmp)
    for need in ("crc32_trap", "crc32_init", "crc32_update"):
        if need not in syms:
            sys.exit("missing symbol " + need)
    if len(blob) > 0x400:
        sys.exit("blob larger than the 1 KB code slot")
    rnd = random.Random(1234)
    data = bytes(rnd.getrandbits(8) for _ in range(1 << 20))
    for base in (0x20000000, 0x20010000):
        for n in (0, 1, 2, 3, 5, 4097, 65539, 1 << 20):
            got = emulate(blob, syms, base, 0x00000000, data[:n], 256 * 1024)
            if got != zlib.crc32(data[:n]):
                sys.exit("emulator mismatch at base 0x%08X len %d" % (base, n))
    words = struct.unpack("<%dI" % (len(blob) // 4), blob)
    with open(OUT, "w") as f:
        f.write("/* SPDX-License-Identifier: MIT */\n")
        f.write("/* GENERATED by loaders/crc32/build.py from loaders/crc32/crc32_ldr.c - do not edit.\n")
        f.write(" * %s; verified in unicorn against zlib.crc32 (lengths 0..1 MiB, two load addresses). */\n" % version)
        f.write("#define ESW_CRC32_LDR_WORDS %du\n" % len(words))
        for name in ("crc32_trap", "crc32_init", "crc32_update"):
            f.write("#define ESW_CRC32_LDR_OFF_%s 0x%02Xu   /* even offsets: Thumb state comes from xPSR.T */\n"
                    % (name.split("_", 1)[1].upper(), syms[name]))
        f.write("static const uint32_t esw_crc32_ldr_blob[ESW_CRC32_LDR_WORDS] = {\n")
        for i in range(0, len(words), 6):
            f.write("    " + ", ".join("0x%08Xu" % w for w in words[i:i + 6]) + ",\n")
        f.write("};\n")
    print("wrote %s: %d bytes, offsets %s, verified" % (os.path.relpath(OUT), len(blob),
          {k: hex(v) for k, v in syms.items()}))


if __name__ == "__main__":
    main()
